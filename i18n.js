const ordered = Object.keys(english).sort((a,b) => b.length-a.length);
const pattern = new RegExp(ordered.map(s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
let locale = 'ja';
const bindings = [];
const issued = new Map();
function remember(value, source) {
  if (issued.size >= 1000) issued.delete(issued.keys().next().value);
  issued.set(value, source); return value;
}
function translate(source) { return locale === 'en' ? (english[source] ?? source.replace(pattern, key => english[key])) : source; }
export function relocalize(value) { return issued.get(value)?.() ?? value; }
export function initialLanguage(saved, languages = globalThis.navigator?.languages, fallback = globalThis.navigator?.language) {
  if (saved === 'ja' || saved === 'en') return saved;
  const primary = Array.isArray(languages) ? languages.find(value => typeof value === 'string' && value.trim()) : '';
  return /^ja(?:-|$)/i.test(String(primary || fallback || '').trim()) ? 'ja' : 'en';
}
export function getLocale() { return locale; }
export function t(source) { return remember(translate(source), () => translate(source)); }
export function lt(parts, ...values) {
  const render = () => parts.reduce((out, part, i) => out + translate(part) + (i < values.length ? values[i] : ''), '');
  return remember(render(), render);
}
export function captureStaticLabels(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!['SCRIPT','STYLE'].includes(node.parentElement?.tagName) && /[ぁ-んァ-ヶ一-龯]/.test(node.data))
      { const source = node.data; bindings.push(() => { node.data = t(source); }); }
  }
  root.querySelectorAll('*').forEach(node => {
    for (const attr of ['title','aria-label','placeholder']) {
      const source = node.getAttribute(attr);
      if (source && /[ぁ-んァ-ヶ一-龯]/.test(source)) bindings.push(() => node.setAttribute(attr, t(source)));
    }
  });
}
export function setLocale(value) {
  locale = value === 'en' ? 'en' : 'ja';
  document.documentElement.lang = locale;
  bindings.forEach(apply => apply());
}
