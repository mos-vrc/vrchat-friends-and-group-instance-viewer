export function t(source) { return remember(translate(source), () => translate(source)); }
export function lt(parts, ...values) {
  const render = () => parts.reduce((out, part, i) => out + translate(part) + (i < values.length ? values[i] : ''), '');
  return remember(render(), render);
}
export function captureStaticLabels(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!['SCRIPT','STYLE'].includes(node.parentElement?.tagName) && /[ぁ-んァ-ヶ一-龯]/.test(node.data))
      { const source = node.data; bindings.push(() => { node.data = t(source); }); }
  }
  root.querySelectorAll('*').forEach(node => {
    for (const attr of ['title','aria-label','placeholder']) {
      const source = node.getAttribute(attr);
      if (source && /[ぁ-んァ-ヶ一-龯]/.test(source)) bindings.push(() => node.setAttribute(attr, t(source)));
    }
  });
}
