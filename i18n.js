const bindings = [];
const issued = new Map();
function remember(value, source) {
  if (issued.size >= 1000) issued.delete(issued.keys().next().value);
  issued.set(value, source); return value;
}
function translate(source) { return locale === 'en' ? (english[source] ?? source.replace(pattern, key => english[key])) : source; }
export function relocalize(value) { return issued.get(value)?.() ?? value; }
export function initialLanguage(saved, languages = globalThis.navigator?.languages, fallback = globalThis.navigator?.language) {
  if (saved === 'ja' || saved === 'en') return saved;
  const primary = Array.isArray(languages) ? languages.find(value => typeof value === 'string' && value.trim()) : '';
  return /^ja(?:-|$)/i.test(String(primary || fallback || '').trim()) ? 'ja' : 'en';
}
